export const STAGE_SETS_STORAGE_KEY = 'quran_quiz_stage_sets_v1';

export function getStoredStageSetNumber(stageId: number): number {
  try {
    const raw = localStorage.getItem(STAGE_SETS_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      return parsed[stageId] === 2 ? 2 : 1;
    }
  } catch (e) {
    console.error('Error reading stage set', e);
  }
  return 1;
}

export function saveStoredStageSetNumber(stageId: number, setNum: number): void {
  try {
    const raw = localStorage.getItem(STAGE_SETS_STORAGE_KEY);
    const parsed = raw ? JSON.parse(raw) : {};
    parsed[stageId] = setNum;
    localStorage.setItem(STAGE_SETS_STORAGE_KEY, JSON.stringify(parsed));
  } catch (e) {
    console.error('Error saving stage set', e);
  }
}

/**
 * دالة استرجاع مجموعة محددة (المجموعة 1 الأساسية أو المجموعة 2 الجديدة بالكامل)
 */
export function getStageQuestionSet(
  stageId: number,
  setNumber: number = 1,
  level: number = 1
): QuizQuestion[] {
  const pool = OFFLINE_STAGE_POOLS[stageId] || OFFLINE_STAGE_POOLS[1];
  
  // Set 1 takes questions 0..9, Set 2 takes questions 10..19
  const sliceStart = setNumber === 2 ? 10 : 0;
  const sliceEnd = setNumber === 2 ? 20 : 10;

  let selected = pool.slice(sliceStart, sliceEnd);
  if (selected.length < 10) {
    selected = pool.slice(0, 10);
  }

  const now = Date.now();
  const result: QuizQuestion[] = selected.map((base, idx) => ({
    ...base,
    id: `set${setNumber}_stg${stageId}_lvl${level}_${now}_${idx + 1}`,
    stage: stageId,
    difficulty: stageId <= 3 ? 'easy' : stageId <= 7 ? 'medium' : 'hard'
  }));

  return result.map(q => shuffleQuestionOptions(q));
}

/**
 * دالة استرجاع أو تدوير 10 أسئلة جديدة وحصرية للمرحلة محلياً (Offline 100%)
 * تقوم بالتبديل بين المجموعة 1 (الأساسية) والمجموعة 2 (الجديدة كلياً بدون أي تكرار)
 */
export function getRefreshedOfflineStageQuestions(
  stageId: number,
  currentQuestionIds: string[] = [],
  level: number = 1
): { questions: QuizQuestion[]; currentSet: number; isReturningToBase: boolean } {
  const currentSet = getStoredStageSetNumber(stageId);
  const nextSet = currentSet === 1 ? 2 : 1;
  const isReturningToBase = nextSet === 1;

  // Save the new set choice for this stage
  saveStoredStageSetNumber(stageId, nextSet);

  const fresh10 = getStageQuestionSet(stageId, nextSet, level);

  return {
    questions: fresh10,
    currentSet: nextSet,
    isReturningToBase
  };
}

