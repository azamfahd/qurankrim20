// Helper functions for reading & storing progress locally
const LOCAL_STORAGE_KEY = 'anis_quran_quiz_user_progress_v2';
const LOCAL_STORAGE_QUESTIONS_KEY = 'anis_quran_quiz_extra_questions_v2';

export interface UserQuizProgress {
  totalScore: number;
  stars: number;
  unlockedStages: number[];
  completedQuestions: string[];
  streak: number;
  highScore: number;
}

export const getStoredUserProgress = (): UserQuizProgress => {
  try {
    const raw = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (raw) {
      return JSON.parse(raw);
    }
  } catch (e) {
    console.error('Error loading quiz progress', e);
  }
  return {
    totalScore: 0,
    stars: 0,
    unlockedStages: [1],
    completedQuestions: [],
    streak: 0,
    highScore: 0,
  };
};

export const saveUserQuizProgress = (progress: UserQuizProgress) => {
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(progress));
  } catch (e) {
    console.error('Error saving quiz progress', e);
  }
};

export const getStoredCustomQuestions = (): QuizQuestion[] => {
  try {
    const raw = localStorage.getItem(LOCAL_STORAGE_QUESTIONS_KEY);
    if (raw) {
      return JSON.parse(raw);
    }
  } catch (e) {
    console.error('Error loading custom AI questions', e);
  }
  return [];
};

export const saveCustomQuestions = (questions: QuizQuestion[]) => {
  try {
    const existing = getStoredCustomQuestions();
    const merged = [...existing, ...questions];
    // Remove duplicates
    const uniqueMap = new Map();
    merged.forEach(q => uniqueMap.set(q.id, q));
    localStorage.setItem(LOCAL_STORAGE_QUESTIONS_KEY, JSON.stringify(Array.from(uniqueMap.values())));
  } catch (e) {
    console.error('Error saving custom AI questions', e);
  }
};

export const getAllQuestions = (): QuizQuestion[] => {
  const customQs = getStoredCustomQuestions();
  const allMap = new Map<string, QuizQuestion>();
  BASE_QUESTIONS.forEach(q => allMap.set(q.id, q));
  customQs.forEach(q => allMap.set(q.id, q));
  return Array.from(allMap.values());
};
