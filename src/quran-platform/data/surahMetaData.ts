/**
 * Returns rich metadata for any given surah (1 to 114).
 * If specific handcrafted metadata exists, it returns it; otherwise,
 * it builds a structured, highly informative fallback dataset.
 */
export function getSurahMetaData(
  number: number,
  name: string,
  revelationType: string = 'Meccan',
  numberOfAyahs: number = 0,
  englishName: string = ''
): SurahMetaDetails {
  if (SURAH_METADATA_MAP[number]) {
    return SURAH_METADATA_MAP[number];
  }

  const cleanName = name.replace(/سُورَةُ\s*/, '').trim();
  const isMeccan = revelationType === 'Meccan' || revelationType === 'مكية';
  const typeText = isMeccan ? 'مكية' : 'مدنية';

  return {
    number,
    name: cleanName,
    titles: [
      `سورة ${cleanName}`,
      isMeccan ? 'سورة مكية ترسيخية' : 'سورة مدنية تشريعية'
    ],
    focus: isMeccan
      ? `ترسيخ عقيدة التوحيد، والإيمان باليوم الآخر، وتزكية النفوس بالصبر والتفكر في آيات الله الكونية.`
      : `تنظيم شؤون الأمة والمجتمع، وبيان الأحكام والتشريعات العادلة، وترسيخ ركائز الأخلاق والعبادات.`,
    themes: [
      `مقاصد التوحيد وعظمة الخالق سبحانه وتعالى في مبادئ سورة ${cleanName}`,
      isMeccan 
        ? `التذكير بالبعث والنشور وضرب الأمثال بالقرون السابقة للاعتبار`
        : `تنظيم العلاقات الاجتماعية والعبادات وتطهير قلوب المؤمنين`,
      `التوجه بالدعاء والإنابة والاستجابة لأوامر الله ونواهيه في آياتها الـ (${numberOfAyahs})`
    ],
    virtues: [
      `سورة كريمة من كلام الله العظيم، تلاوتها بالحرف تدخلك في أجر العشر حسنات.`,
      `تضم آيات بيّنات تهدى بها القلوب وتنزك بها النفوس وتتنزل بها السكينة.`,
      `قراءتها بتدبر تزيد في إيمان العبد وتمنحه الطمأنينة والنور.`
    ],
    practicalActions: [
      `تدبر معاني آيات سورة ${cleanName} والعمل بمقتضى أوامرها وتجنب نواهيها.`,
      `المواظبة على تلاوتها وتكرار آياتها في الصلوات والنوافل.`,
      `التخلق بالأخلاق الكريمة والاستعانة بالله في تطبيق هدايات السورة.`
    ],
    historicalContext: `سورة ${typeText}، ترتيب نزولها الشريف من أسرار الحكمة الإلهية في تدرج الوحي المبارك.`
  };
}
