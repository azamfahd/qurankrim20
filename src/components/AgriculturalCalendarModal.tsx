const getDailyEmojis = (monthName: string, dayNumber: number, season: string) => {
  const monthData = HIMYARITE_MONTH_EMOJIS[monthName] || { main: '🌾', weather: '☀️', crops: ['🌱', '🌿'], iconLabel: 'موسم زراعي' };
  
  let seasonEmoji = '🌸';
  if (season === 'الصيف') seasonEmoji = '☀️';
  else if (season === 'الخريف') seasonEmoji = '🍂';
  else if (season === 'الشتاء') seasonEmoji = '❄️';

  const dayEmojiOptions = ['🌱', '🌾', '💧', '☀️', '🍃', '🌸', '🍇', '🌽', '🧄', '🥔'];
  const daySpecificEmoji = dayEmojiOptions[(dayNumber + monthName.length) % dayEmojiOptions.length];

  return {
    primary: monthData.main,
    weather: monthData.weather,
    season: seasonEmoji,
    dayEmoji: daySpecificEmoji,
    cropEmojis: monthData.crops,
    iconLabel: monthData.iconLabel
  };
};

const getDaysInGregorianMonth = (monthNumber: number, year: number): number => {
  return new Date(year, monthNumber, 0).getDate();
};

const getDetailProgressInfo = (
  type: 'himyarite' | 'syriac' | 'marker',
  data: any,
  today: Date
) => {
  const todayDetails = getAgriculturalDetails(today);
  const currentYear = today.getFullYear();

  if (type === 'himyarite') {
    const isCurrent = data.name === todayDetails.himyariteMonth.name;
    const totalDays = data.duration || 30;
    const daysPassed = isCurrent ? todayDetails.himyariteDay : 0;
    const daysRemaining = isCurrent ? Math.max(0, totalDays - daysPassed) : 0;
    const progressPercent = isCurrent ? Math.min(100, Math.round((daysPassed / totalDays) * 100)) : 0;

    return {
      isCurrent,
      totalDays,
      daysPassed,
      daysRemaining,
      progressPercent
    };
  } else if (type === 'syriac') {
    const currentMonthNum = today.getMonth() + 1;
    const isCurrent = data.number === currentMonthNum;
    const totalDays = getDaysInGregorianMonth(data.number, currentYear);
    const daysPassed = isCurrent ? today.getDate() : 0;
    const daysRemaining = isCurrent ? Math.max(0, totalDays - daysPassed) : 0;
    const progressPercent = isCurrent ? Math.min(100, Math.round((daysPassed / totalDays) * 100)) : 0;

    return {
      isCurrent,
      totalDays,
      daysPassed,
      daysRemaining,
      progressPercent
    };
  } else {
    // Marker
    const isCurrent = data.manzil === todayDetails.marker.manzil;
    const totalDays = (data.manzil === 'الصلم' || data.marker === 'الصلم') ? 11 : 13;
    const daysPassed = isCurrent ? todayDetails.markerDay : 0;
    const daysRemaining = isCurrent ? Math.max(0, totalDays - daysPassed) : 0;
    const progressPercent = isCurrent ? Math.min(100, Math.round((daysPassed / totalDays) * 100)) : 0;

    return {
      isCurrent,
      totalDays,
      daysPassed,
      daysRemaining,
      progressPercent
    };
  }
};

