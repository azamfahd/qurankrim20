export const detectRegionFromLocationName = (locationName?: string): string => {
  if (!locationName) return 'highlands';
  
  const norm = (str: string) => 
    str.replace(/[إأآا]/g, 'ا')
       .replace(/ة/g, 'ه')
       .replace(/ى/g, 'ي')
       .replace(/\s+/g, '')
       .toLowerCase();

  const name = norm(locationName);
  
  // Coastal & Tihama
  if (name.includes('الحديده') || name.includes('عدن') || name.includes('لحج') || name.includes('ابين') || name.includes('تهامه') || name.includes('زبيد') || name.includes('مخا') || name.includes('سقطري')) {
    return 'coastal';
  }
  
  // Eastern & Valleys
  if (name.includes('حضرموت') || name.includes('المكلا') || name.includes('سييون') || name.includes('تريم') || name.includes('شبوه') || name.includes('عتق') || name.includes('مارب') || name.includes('الجوف') || name.includes('المهره') || name.includes('الغيضه')) {
    return 'eastern';
  }
  
  // Middle & Terraces
  if (name.includes('اب') || name.includes('تعز') || name.includes('ريمه') || name.includes('المحويت') || name.includes('حجه') || name.includes('يريم') || name.includes('العدين') || name.includes('جبله')) {
    return 'middle';
  }
  
  // Highlands (Default)
  return 'highlands';
};

const getRegionalData = (monthNum: number, regionId: string): { region: YemenRegionConfig; monthDetail: RegionalMonthDetail } => {
  const reg = YEMEN_REGIONS.find(r => r.id === regionId) || YEMEN_REGIONS[0];
  const m = reg.months[monthNum] || reg.months[1];
  return { region: reg, monthDetail: m };
};


